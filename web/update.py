#!/usr/bin/env python3
"""Assemble the static NNLOJET site from page fragments and the generated manual."""
from __future__ import annotations

import argparse
import html
import json
import shutil
from pathlib import Path
from urllib.parse import unquote, urlsplit

from lxml import html as lhtml

WEB = Path(__file__).resolve().parent
BUILD = WEB.parent / '_build' / 'manual'
OUTPUT = WEB / 'autogenerated'
PAGES = {
    'index.html': 'Home',
    'processes.html': 'Processes',
    'releases.html': 'Releases',
    'quickstart.html': 'Quick start',
    'examples.html': 'Examples',
    'manual.html': 'Manual (HTML)',
    'nnlojet-manual.pdf': 'Manual (PDF)',
    'faq.html': 'FAQ',
    'collaboration.html': 'Collaboration',
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--preview', action='store_true', help='Local-only preview: disable unavailable release downloads instead of failing.')
    args = parser.parse_args()
    required = [BUILD / 'manual.pdf', BUILD / 'navigation.json', BUILD / 'lwarp.js', BUILD / 'fragments/manual.html']
    if any(not p.is_file() for p in required):
        raise SystemExit('Build the manual first: bash web/make_manual.sh (from the repository root).')
    navigation = json.loads((BUILD / 'navigation.json').read_text(encoding='utf-8'))
    manual_names = ['manual.html'] + [p['file'] for p in navigation]
    contents = {name: (BUILD / 'fragments' / name).read_text(encoding='utf-8') for name in manual_names}
    for name in PAGES:
        if name.endswith('.html') and name not in contents:
            contents[name] = (WEB / name).read_text(encoding='utf-8')
    # Discover local release packages from the actual page; external Release URLs
    # need no matching file in this repository and no change to this builder.
    release_doc = lhtml.fragment_fromstring(contents['releases.html'], create_parent='div')
    release_assets = {}
    missing = []
    for link in release_doc.xpath('.//a[@href]'):
        url = urlsplit(link.get('href'))
        if url.scheme or url.netloc or not url.path.endswith('.tar.gz'):
            continue
        relative = Path(unquote(url.path))
        if relative.is_absolute() or '..' in relative.parts:
            raise SystemExit(f'Unsafe release path: {relative}')
        if not (WEB / relative).is_file():
            missing.append(str(relative))
            if args.preview:
                link.attrib.pop('href')
                link.set('title', 'Download unavailable in this local preview')
        else:
            release_assets[relative] = WEB / relative
    if missing and not args.preview:
        raise SystemExit('Missing software release downloads:\n  ' + '\n  '.join(missing) +
                         '\nRestore them under web/, or change releases.html to real external Release URLs.\n'
                         'For a non-publishable local preview only: python3 web/update.py --preview')
    if args.preview:
        contents['releases.html'] = ''.join(lhtml.tostring(c, encoding='unicode') for c in release_doc)
    template = (WEB / 'TEMPLATE.html').read_text(encoding='utf-8')
    template = template.replace('CSS1\n', '<link rel="stylesheet" href="index_files/hepforge.css">\n')
    template = template.replace('CSS2\n', '<link rel="stylesheet" href="index_files/hepforge-override.css">\n')
    notice = '<p role="status"><strong>Local preview — not for publication.</strong> Unavailable release downloads are disabled.</p>' if args.preview else ''
    template = template.replace('BANNER\n', notice)
    manual_scripts = '''<link rel="stylesheet" href="index_files/hepforge-override-manual.css">
<script src="index_files/lwarp.js"></script>
<script id="MathJax-script" async src="https://cdn.jsdelivr.net/npm/mathjax@3.2.2/es5/tex-mml-chtml.js"></script>'''
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    for folder in ['index_files', 'runcards', 'example_runs']:
        shutil.copytree(WEB / folder, OUTPUT / folder)
    for name in ['nnlogo.svg', 'NNLOJET_meeting_2025.jpg', 'exampleZ.run']:
        shutil.copy2(WEB / name, OUTPUT / name)
    for pattern in ['*.png', '*.svg']:
        for path in (BUILD / 'html').glob(pattern):
            shutil.copy2(path, OUTPUT / path.name)
    for path in (BUILD / 'html').glob('*-images'):
        if path.is_dir():
            shutil.copytree(path, OUTPUT / path.name)
    shutil.copy2(BUILD / 'lwarp.js', OUTPUT / 'index_files/lwarp.js')
    for name in ['nnlojet-manual.pdf', 'nnlojet-v1.0.0.pdf']:
        shutil.copy2(BUILD / 'manual.pdf', OUTPUT / name)
    for relative, source in release_assets.items():
        (OUTPUT / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, OUTPUT / relative)
    for name, content in contents.items():
        sidebar = []
        for target, title in PAGES.items():
            children = ''
            if target == 'manual.html' and name in manual_names:
                children = '<ol>' + ''.join(f'<li><a href="{html.escape(p["file"], quote=True)}">{html.escape(p["title"])}</a></li>' for p in navigation) + '</ol>'
            new_tab = ' target="_blank" rel="noopener"' if target.endswith('.pdf') else ''
            sidebar.append(f'<li><a href="{target}"{new_tab}>{title}</a>{children}</li>')
        page = (template.replace('SIDEBAR', '\n'.join(sidebar))
                .replace('MANUAL\n', manual_scripts if name in manual_names else '')
                .replace('CONTENT', content))
        # Repair legacy fragment nesting locally, rather than relying on HEPForge.
        doc = lhtml.document_fromstring(page)
        doc.set('lang', 'en')
        (OUTPUT / name).write_text(lhtml.tostring(doc, encoding='unicode', method='html', doctype='<!DOCTYPE html>'), encoding='utf-8')
    (OUTPUT / '.nojekyll').touch()
    if args.preview:
        (OUTPUT / '.preview').touch()
    print(f'Built {len(contents)} pages in {OUTPUT}' + (' (PREVIEW ONLY)' if args.preview else ''))


if __name__ == '__main__':
    main()
