#!/usr/bin/env python3
"""Check local HTML links and anchors before a Pages upload (no network access)."""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit


class Page(HTMLParser):
    def __init__(self, text: str) -> None:
        super().__init__(convert_charrefs=True)
        self.ids: set[str] = set()
        self.links: list[str] = []
        self.duplicates: set[str] = set()
        self.feed(text)

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = dict(attrs)
        ident = values.get('id') or (values.get('name') if tag == 'a' else None)
        if ident:
            if ident in self.ids:
                self.duplicates.add(ident)
            self.ids.add(ident)
        for attr in ['href', 'src']:
            if values.get(attr):
                self.links.append(values[attr])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', nargs='?', type=Path, default=Path(__file__).resolve().parent / 'autogenerated')
    parser.add_argument('--preview', action='store_true', help='Allow a deliberately marked local preview.')
    args = parser.parse_args()
    root = args.directory.resolve()
    if not (root / 'index.html').is_file():
        raise SystemExit('Missing index.html; build the website first.')
    if (root / '.preview').exists() and not args.preview:
        raise SystemExit('Refusing publication: this is a local preview with unavailable release downloads.')
    pages = {p.resolve(): Page(p.read_text(encoding='utf-8')) for p in root.rglob('*.html')}
    errors: set[str] = set()
    checked = 0
    for source, page in pages.items():
        for duplicate in page.duplicates:
            errors.add(f'{source.name}: duplicate id {duplicate}')
        for link in page.links:
            url = urlsplit(link)
            if url.scheme or url.netloc or not link or link == '#':
                continue
            checked += 1
            if url.path.startswith('/'):
                errors.add(f'{source.name}: root-absolute URL may break a project site: {link}')
                continue
            target = (source.parent / unquote(url.path)).resolve() if url.path else source
            if target.is_dir():
                target = target / 'index.html'
            if not target.is_relative_to(root) or not target.is_file():
                errors.add(f'{source.name}: missing local file: {link}')
            elif url.fragment and target in pages and unquote(url.fragment) not in pages[target].ids:
                errors.add(f'{source.name}: missing HTML anchor: {link}')
    if errors:
        raise SystemExit('Website validation failed:\n  '+'\n  '.join(sorted(errors)))
    print(f'Validated {len(pages)} pages and {checked} local HTML href/src references.')


if __name__ == '__main__':
    main()
